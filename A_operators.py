# Addition op
a = 10
b = 25
print("This is sum of a and b:", a+b)

# Subtraction op
A = 50
B = 36
print("This is subtraction of  A - B:", A - B)

# Multiplication op
c = 300
d = 27
print("This is multiplication of c and d:", c*d)

# Division op
e = 2379
f = 82
print("This is division e/f:", e/f)

# Floor division
# This op skips values after decimal
g = 155
h = 4
print("Floor division b/w g and h:", g // h)

# Modulus operator
# returns remainder when division is performed
i = 56
j = 7
print(56/7, ": This is remainder obtained from division of 56/7")